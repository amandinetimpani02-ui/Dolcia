export function validateDecisionCodes(codes = []) {
  const unknown = codes.filter(code => !DECISION_CODE_SET.has(code));
  const contradictions = [];
  for (const [family, members] of Object.entries(CODE_FAMILIES)) {
    const present = members.filter(code => codes.includes(code));
    if (present.length > 1) contradictions.push({ family, codes: present });
  }
  return { valid: unknown.length === 0 && contradictions.length === 0, unknown, contradictions };
}
